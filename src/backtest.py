"""Recursive multi-step forecasting backtest and rolling-origin evaluation module.

Protocol & Integrity Guarantees:
- Strict chronological rolling-origin evaluation across held-out test intervals.
- For every forecast origin T_origin, predictions utilize ONLY observations at or before T_origin.
- Recursive predictions generated by step s are fed into lags/rolling windows for subsequent steps;
  actual target observations within the forecast window are NEVER leaked into feature construction.
- Origins are evaluated across horizons H in [1, 6, 24, 48] hours.
- Origins lacking the complete 168-hour lookback window or lacking complete actuals across the target
  evaluation window are strictly skipped and audited.
- Both Random Forest and Persistence baselines are evaluated on the exact same (origin, horizon) pairs.
"""

import json
import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple, Union

import numpy as np
import pandas as pd

from src.forecast import generate_forecast, load_forecasting_model

logger = logging.getLogger(__name__)

DEFAULT_HORIZONS: Tuple[int, ...] = (1, 6, 24, 48)
DEFAULT_METRICS_PATH: Path = Path("outputs/metrics/recursive_backtest_metrics.json")
MIN_REQUIRED_LOOKBACK_HOURS: int = 168


def run_recursive_backtest(
    model_or_path: Union[str, Path, Dict[str, Any]],
    data_or_path: Union[str, Path, pd.DataFrame] = Path("data/processed/hourly_energy.csv"),
    horizons: Sequence[int] = DEFAULT_HORIZONS,
    origin_stride_hours: int = 72,
    start_origin: Optional[Union[str, pd.Timestamp]] = None,
    end_origin: Optional[Union[str, pd.Timestamp]] = None,
    output_metrics_path: Optional[Union[str, Path]] = DEFAULT_METRICS_PATH,
) -> Dict[str, Any]:
    """Execute leakage-safe rolling-origin backtest for multi-step recursive forecasting.

    Args:
        model_or_path: Path to serialized model joblib artifact or loaded model payload dict.
        data_or_path: Processed hourly dataset DataFrame or CSV file path.
        horizons: Sequence of forecast horizons in hours (e.g., [1, 6, 24, 48]).
        origin_stride_hours: Stride in hours between evaluated origins (default: 72 hours).
        start_origin: Earliest candidate origin timestamp. Defaults to test split start
                      (2010-04-18 18:00:00) to ensure strictly held-out evaluation.
        end_origin: Latest candidate origin timestamp. Defaults to test split end minus max horizon.
        output_metrics_path: Path to save the resulting metrics JSON.

    Returns:
        Dict[str, Any]: Comprehensive backtest results, sample counts, and horizon metrics.
    """
    # 1. Load model artifact
    if isinstance(model_or_path, (str, Path)):
        payload = load_forecasting_model(model_or_path)
    elif isinstance(model_or_path, dict):
        payload = model_or_path
    else:
        raise ValueError(f"Invalid model_or_path argument: {type(model_or_path)}")

    # 2. Load dataset
    if isinstance(data_or_path, (str, Path)):
        df = pd.read_csv(data_or_path)
    elif isinstance(data_or_path, pd.DataFrame):
        df = data_or_path.copy()
    else:
        raise ValueError(f"Invalid data_or_path argument: {type(data_or_path)}")

    # Normalize timestamp
    ts_col = "timestamp" if "timestamp" in df.columns else "datetime"
    df["timestamp"] = pd.to_datetime(df[ts_col])
    df = df.sort_values("timestamp").reset_index(drop=True)

    target_col = payload.get("target_col", "energy_kwh")
    if target_col not in df.columns:
        raise ValueError(f"Target column '{target_col}' not found in dataset columns: {list(df.columns)}")

    # Fast O(1) timestamp lookup map for actuals
    ts_actuals_map: Dict[pd.Timestamp, float] = dict(zip(df["timestamp"], df[target_col]))

    # Validate horizons
    sorted_horizons = sorted(list(set(horizons)))
    for h in sorted_horizons:
        if not (1 <= h <= 168):
            raise ValueError(f"Horizon {h} outside valid range [1, 168].")
    max_horizon = max(sorted_horizons)

    # 3. Determine candidate origin boundaries
    # Default to Phase 4A held-out test split (2010-04-18 18:00:00 to 2010-11-26 20:00:00)
    dataset_min_ts = df["timestamp"].iloc[0]
    dataset_max_ts = df["timestamp"].iloc[-1]

    if start_origin is not None:
        origin_start_ts = pd.Timestamp(start_origin)
    else:
        # Held-out test period start from Phase 4A split
        origin_start_ts = pd.Timestamp("2010-04-18 18:00:00").ceil("D")

    if end_origin is not None:
        origin_end_ts = pd.Timestamp(end_origin)
    else:
        # Must leave room for max_horizon forward evaluation steps
        origin_end_ts = dataset_max_ts.floor("D") - pd.Timedelta(hours=max_horizon)

    if origin_start_ts >= origin_end_ts:
        raise ValueError(
            f"Invalid origin range: start_origin ({origin_start_ts}) >= end_origin ({origin_end_ts})"
        )

    candidate_origins = pd.date_range(
        start=origin_start_ts,
        end=origin_end_ts,
        freq=f"{origin_stride_hours}h",
    )

    logger.info(
        "Evaluating %d candidate origins (stride=%dh) from %s to %s.",
        len(candidate_origins),
        origin_stride_hours,
        origin_start_ts,
        origin_end_ts,
    )

    # 4. Rolling-origin execution
    eligible_origins: List[str] = []
    skipped_history_gaps: int = 0
    skipped_target_gaps: int = 0

    rf_errors_by_horizon: Dict[int, List[float]] = {h: [] for h in sorted_horizons}
    persist_errors_by_horizon: Dict[int, List[float]] = {h: [] for h in sorted_horizons}

    for origin in candidate_origins:
        # A. Verify required contiguous historical lookback (168 hours up to origin)
        hist_needed = [origin - pd.Timedelta(hours=k) for k in range(MIN_REQUIRED_LOOKBACK_HOURS)]
        if not all(t in ts_actuals_map and np.isfinite(ts_actuals_map[t]) for t in hist_needed):
            skipped_history_gaps += 1
            continue

        # B. Verify required forward evaluation target actuals (1 to max_horizon)
        target_needed = [origin + pd.Timedelta(hours=s) for s in range(1, max_horizon + 1)]
        if not all(t in ts_actuals_map and np.isfinite(ts_actuals_map[t]) for t in target_needed):
            skipped_target_gaps += 1
            continue

        # C. Strictly partition data at or before origin (zero lookahead)
        hist_slice = df[df["timestamp"] <= origin].copy()

        # D. Generate recursive forecast rollout
        forecast_df = generate_forecast(
            model_or_path=payload,
            history=hist_slice,
            horizon_hours=max_horizon,
        )

        step_to_pred = dict(zip(forecast_df["step"], forecast_df["forecast_energy_kwh"]))
        origin_last_actual = ts_actuals_map[origin]

        # E. Record errors for each horizon
        eligible_origins.append(str(origin))
        for h in sorted_horizons:
            actual_val = ts_actuals_map[origin + pd.Timedelta(hours=h)]
            rf_pred = step_to_pred[h]
            persist_pred = origin_last_actual  # Last observed value baseline

            rf_errors_by_horizon[h].append(rf_pred - actual_val)
            persist_errors_by_horizon[h].append(persist_pred - actual_val)

    # 5. Compute aggregate metrics per horizon
    horizon_results: Dict[str, Dict[str, Any]] = {}
    total_evaluated_origins = len(eligible_origins)

    for h in sorted_horizons:
        rf_errs = np.array(rf_errors_by_horizon[h], dtype=np.float64)
        p_errs = np.array(persist_errors_by_horizon[h], dtype=np.float64)

        if len(rf_errs) > 0:
            rf_mae = float(np.mean(np.abs(rf_errs)))
            rf_rmse = float(np.sqrt(np.mean(rf_errs**2)))
            p_mae = float(np.mean(np.abs(p_errs)))
            p_rmse = float(np.sqrt(np.mean(p_errs**2)))
        else:
            rf_mae, rf_rmse, p_mae, p_rmse = float("nan"), float("nan"), float("nan"), float("nan")

        horizon_results[f"horizon_{h}h"] = {
            "horizon_hours": h,
            "evaluated_origins": len(rf_errs),
            "unit": "kWh",
            "random_forest": {
                "mae": round(rf_mae, 6),
                "rmse": round(rf_rmse, 6),
            },
            "persistence": {
                "mae": round(p_mae, 6),
                "rmse": round(p_rmse, 6),
            },
            "rf_mae_improvement_pct": (
                round(((p_mae - rf_mae) / p_mae) * 100.0, 2)
                if (p_mae > 0 and np.isfinite(rf_mae) and np.isfinite(p_mae))
                else None
            ),
        }

    backtest_report: Dict[str, Any] = {
        "backtest_protocol": "Chronological rolling-origin evaluation without lookahead leakage",
        "target_column": target_col,
        "target_units": "kWh",
        "model_evaluated": payload.get("model_type", "random_forest"),
        "baseline_evaluated": "Persistence (Last Observed Value at Forecast Origin)",
        "evaluation_partition": "Held-out test set (2010-04-18 to 2010-11-26, post-training)",
        "origin_range": {
            "requested_start": str(origin_start_ts),
            "requested_end": str(origin_end_ts),
            "first_eligible_origin": eligible_origins[0] if eligible_origins else None,
            "last_eligible_origin": eligible_origins[-1] if eligible_origins else None,
            "origin_stride_hours": origin_stride_hours,
            "window_overlap_policy": (
                "Disjoint evaluation windows: 72h stride exceeds 48h max horizon, "
                "ensuring zero target timestamp overlap between successive origins."
                if origin_stride_hours >= max_horizon
                else "Overlapping evaluation windows: stride is less than max horizon."
            ),
        },
        "origin_accounting": {
            "total_candidate_origins": len(candidate_origins),
            "eligible_origins": total_evaluated_origins,
            "skipped_origins_total": skipped_history_gaps + skipped_target_gaps,
            "skipped_due_to_history_gaps": skipped_history_gaps,
            "skipped_due_to_target_gaps": skipped_target_gaps,
        },
        "horizons_evaluated": list(sorted_horizons),
        "horizon_metrics": horizon_results,
        "limitations": [
            "Evaluated exclusively on a single French household dataset (2006-2010); findings cannot be generalized to commercial buildings or diverse climate zones.",
            "Historical backtest results do not constitute live predictions for the present year (2026).",
            "Recursive forecasting feeds step predictions into subsequent lag and rolling features; prediction errors naturally compound over extended horizons.",
            "Requires 168 strictly contiguous historical hours; telemetry outages require fallback mechanisms in production."
        ],
    }

    # Save to JSON
    if output_metrics_path is not None:
        out_path = Path(output_metrics_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            json.dump(backtest_report, f, indent=2)
        logger.info("Saved backtest report to '%s'.", out_path.resolve())

    return backtest_report
